#!/usr/bin/env python3
"""Export evals/cases.jsonl into the layout `claude plugin eval` runs. Stdlib only.

  python scripts/export_evals.py            # writes quality/evals/<skill>-<nn>/...
  python scripts/export_evals.py --check    # exit 1 if the exported folder is out of date

evals/cases.jsonl stays the single place behavioural cases are written and counted
by the validator. This script derives, for every case, a prompt.md (the query), an
llm grader (the expected behaviours as a PASS/FAIL rubric) and a tool_used grader
that confirms the named skill actually fired.

evals/triggers.jsonl holds the triggering tests from the Claude skills guide: an
"obvious" and a "paraphrase" query must load the skill, an "unrelated" query must
not. Each becomes a case with one tool_used grader (min 1, or min 0 and max 0).

A skill with disable-model-invocation: true is started by a person, so the model never
loads it on its own. It gets no trigger cases. Its behavioural cases start with the
slash command (/<plugin>:<skill>), skip the skill-fired grader and are judged on the
rubric alone.

Run the exported suite from the plugin root (it calls the model, so it uses your
plan or API credits; add --ablation none to skip the no-plugin comparison and halve
the cost):

  claude plugin eval . --eval-dir quality/evals

Do not edit quality/evals by hand. Change cases.jsonl and export again.
"""

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / "evals" / "cases.jsonl"
TRIGGERS = ROOT / "evals" / "triggers.jsonl"
OUT = ROOT / "quality" / "evals"
MARKER = "<!-- generated by scripts/export_evals.py: edit evals/cases.jsonl instead -->"
ALLOWED_TOOLS = "[Read, Glob, Grep, Skill]"


def user_only_skills():
    """Skills a person starts by name (disable-model-invocation: true). The model never loads them on its own."""
    out = set()
    for path in (ROOT / "skills").glob("*/SKILL.md"):
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
        if m and re.search(r"(?m)^disable-model-invocation:\s*[\"']?true", m.group(1)):
            out.add(path.parent.name)
    return out


def plugin_name():
    manifest = ROOT / ".claude-plugin" / "plugin.json"
    return json.loads(manifest.read_text(encoding="utf-8"))["name"]


def load_cases():
    cases = []
    for number, line in enumerate(CASES.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip():
            try:
                cases.append(json.loads(line))
            except json.JSONDecodeError as exc:
                sys.exit(f"ERROR: evals/cases.jsonl:{number}: invalid JSON ({exc})")
    return cases


def load_triggers():
    triggers = []
    if not TRIGGERS.exists():
        return triggers
    for number, line in enumerate(TRIGGERS.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip():
            try:
                triggers.append(json.loads(line))
            except json.JSONDecodeError as exc:
                sys.exit(f"ERROR: evals/triggers.jsonl:{number}: invalid JSON ({exc})")
    return triggers


def render_triggers(triggers):
    """Return {relative path: file text} for the triggering cases."""
    files = {}
    counters = {}
    user_only = user_only_skills()
    for trig in triggers:
        skill = trig["skill"]
        if skill in user_only:
            continue
        counters[skill] = counters.get(skill, 0) + 1
        name = f"{skill}-trigger-{counters[skill]:02d}"
        files[f"{name}/prompt.md"] = (
            f"---\nmax_turns: 3\nallowed_tools: {ALLOWED_TOOLS}\n---\n\n{trig['query'].strip()}\n"
        )
        pattern = rf'"skill"\s*:\s*"(?:[\w-]+:)?{skill}"'
        bounds = "min: 0\nmax: 0\n" if trig["type"] == "unrelated" else "min: 1\n"
        files[f"{name}/graders/skill-fired.md"] = (
            f"---\ntype: tool_used\ntool: Skill\ninput_match: '{pattern}'\n{bounds}---\n"
        )
    return files


def render(cases):
    """Return {relative path: file text} for every exported file."""
    files = {}
    counters = {}
    user_only = user_only_skills()
    for case in cases:
        skills = case.get("skills") or ["unassigned"]
        primary = skills[0]
        counters[primary] = counters.get(primary, 0) + 1
        name = f"{primary}-{counters[primary]:02d}"
        query = case["query"].strip()
        if primary in user_only:
            query = f"/{plugin_name()}:{primary} {query}"
        files[f"{name}/prompt.md"] = (
            f"---\nmax_turns: 10\nallowed_tools: {ALLOWED_TOOLS}\n---\n\n{query}\n"
        )
        expected = case.get("expected_behavior") or []
        rubric = "\n".join(f"- {item}" for item in expected)
        files[f"{name}/graders/criteria.md"] = (
            "---\ntype: llm\n---\n\n"
            f"{MARKER}\n\n"
            "The agent in this run can read and search files but cannot write them, so judge what it says it would do\n"
            "and what it proposes, not files it created.\n\n"
            "PASS if the response does all of the following:\n"
            f"{rubric}\n\n"
            "FAIL if any of them is missing, or if the response does the opposite of one.\n"
        )
        if primary not in user_only:
            pattern = rf'"skill"\s*:\s*"(?:[\w-]+:)?{primary}"'
            files[f"{name}/graders/skill-fired.md"] = (
                f"---\ntype: tool_used\ntool: Skill\ninput_match: '{pattern}'\n---\n"
            )
    files.update(render_triggers(load_triggers()))
    return files


def main():
    if not CASES.exists():
        sys.exit("ERROR: evals/cases.jsonl not found")
    files = render(load_cases())
    if "--check" in sys.argv:
        stale = []
        for rel, text in files.items():
            path = OUT / rel
            if (
                not path.exists()
                or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text
            ):
                stale.append(rel)
        existing = (
            {
                p.relative_to(OUT).as_posix()
                for p in OUT.rglob("*")
                if p.is_file() and "results" not in p.parts
            }
            if OUT.exists()
            else set()
        )
        stale += sorted(existing - set(files))
        if stale:
            print(
                "ERROR: quality/evals is out of date; run `python scripts/export_evals.py`:"
            )
            for rel in stale[:10]:
                print("  ", rel)
            return 1
        print(f"export_evals: ok ({len(files)} files)")
        return 0
    if OUT.exists():
        for child in OUT.iterdir():
            if child.name != "results":
                shutil.rmtree(child) if child.is_dir() else child.unlink()
    for rel, text in files.items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    print(
        f"exported {len(load_cases()) + len(load_triggers())} cases to {OUT.relative_to(ROOT).as_posix()}/"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
